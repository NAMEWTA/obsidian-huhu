type claimFixtureFile struct {
	Path, SHA256 string
	Size         int64
	Mode         int64
	Directory    bool
}

type claimFixtureRun struct {
	ID, RootID, ParentID, State string
	Slot                        int
}

type claimFixtureFacts struct {
	ProfileID, CommandEpoch string
	Schema                  int
	Runs                    []claimFixtureRun
	RootLimits              map[string]api.ExecutionLimits
}

type claimFixtureManifest struct {
	Format                 int
	Trees                  int
	Roots                  []string
	Limits                 api.ExecutionLimits
	Facts                  claimFixtureFacts
	Files                  []claimFixtureFile
	ArchiveSHA256          string
	GenerationSourceFiles  map[string]string
	GenerationSourceSHA256 string
}

func claimDigest(data []byte) string {
	h := sha256.Sum256(data)
	return hex.EncodeToString(h[:])
}

func claimFixtureDirectory(trees int) string {
	return filepath.Join("testdata", "claim-fairness", fmt.Sprintf("%d-trees", trees))
}

// These reads do not bootstrap, recover, delete pins or change business facts.
// The same complete rows and limits are checked again on a copied fixture.
func claimReadFixtureFacts(t *testing.T, loc string, roots []string) claimFixtureFacts {
	t.Helper()
	u := url.URL{Scheme: "file", Path: filepath.Join(loc, "profile.sqlite3"), RawQuery: "mode=ro"}
	db, e := sql.Open("sqlite3", u.String())
	if e != nil {
		t.Fatal(e)
	}
	defer db.Close()
	facts := claimFixtureFacts{Runs: []claimFixtureRun{}, RootLimits: map[string]api.ExecutionLimits{}}
	if e = db.QueryRow("PRAGMA user_version").Scan(&facts.Schema); e != nil {
		t.Fatal(e)
	}
	if e = db.QueryRow("SELECT profile_id,CAST(command_epoch AS TEXT) FROM profile_metadata WHERE singleton=1").Scan(&facts.ProfileID, &facts.CommandEpoch); e != nil {
		t.Fatal(e)
	}
	var checkpoints int
	if e = db.QueryRow("SELECT count(*) FROM execution_checkpoints").Scan(&checkpoints); e != nil || checkpoints != 0 {
		t.Fatal("unexpected checkpoint in source-free held-producer setup", checkpoints, e)
	}
	rows, e := db.Query("SELECT run_id,root_run_id,parent_run_id,status,child_slot FROM execution_runs ORDER BY run_id")
	if e != nil {
		t.Fatal(e)
	}
	for rows.Next() {
		var r claimFixtureRun
		if e = rows.Scan(&r.ID, &r.RootID, &r.ParentID, &r.State, &r.Slot); e != nil {
			_ = rows.Close()
			t.Fatal(e)
		}
		facts.Runs = append(facts.Runs, r)
	}
	e = rows.Err()
	closeErr := rows.Close()
	if e != nil || closeErr != nil {
		t.Fatal(e, closeErr)
	}
	for _, id := range roots {
		var raw string
		if e = db.QueryRow("SELECT policy_json FROM collaboration_policy_roots WHERE root_run_id=?", id).Scan(&raw); e != nil {
			t.Fatal(e)
		}
		var limits api.ExecutionLimits
		if e = json.Unmarshal([]byte(raw), &limits); e != nil {
			t.Fatal(e)
		}
		facts.RootLimits[id] = limits
	}
	return facts
}

// Provenance records production and all generating package code, never its
// own output archives/manifests. Future recovery inputs may retain this honest
// historical provenance; loading verifies fixture bytes, not a fictional new
// claim that an older fixture was regenerated by every later production edit.
func claimGenerationSources(t *testing.T) (map[string]string, string) {
	t.Helper()
	module, e := filepath.Abs("../../..")
	if e != nil {
		t.Fatal(e)
	}
	packageDir, e := os.Getwd()
	if e != nil {
		t.Fatal(e)
	}
	paths := []string{filepath.Join(module, "go.mod"), filepath.Join(module, "go.sum"), filepath.Join(packageDir, "testdata", "claim-fairness", "README.md")}
	for _, dir := range []string{filepath.Join(module, "internal"), filepath.Join(module, "cmd"), packageDir} {
		e := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() && d.Name() == "testdata" {
				return filepath.SkipDir
			}
			if !d.IsDir() && (strings.HasSuffix(path, ".go") || strings.HasSuffix(path, ".sql")) {
				paths = append(paths, path)
			}
			return nil
		})
		if e != nil {
			t.Fatal(e)
		}
	}
	files := map[string]string{}
	for _, path := range paths {
		b, e := os.ReadFile(path)
		if e != nil {
			t.Fatal(e)
		}
		rel, e := filepath.Rel(module, path)
		if e != nil {
			t.Fatal(e)
		}
		files[filepath.ToSlash(rel)] = claimDigest(b)
	}
	return files, claimSourceDigest(files)
}

func claimSourceDigest(files map[string]string) string {
	keys := make([]string, 0, len(files))
	for key := range files {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var canonical strings.Builder
	for _, key := range keys {
		fmt.Fprintf(&canonical, "%s  %s\n", files[key], key)
	}
	return claimDigest([]byte(canonical.String()))
}

func claimVerifyFixtureFacts(t *testing.T, m claimFixtureManifest) {
	t.Helper()
	if m.Format != 1 || (m.Trees != 4 && m.Trees != 6) || len(m.Roots) != m.Trees || len(m.Facts.Runs) != m.Trees*33 {
		t.Fatal("invalid complete fixture identity/count", m.Format, m.Trees, len(m.Roots), len(m.Facts.Runs))
	}
	expected := api.ExecutionLimits{MaxDepth: 3, MaxChildren: 32, RootChildren: 1, ProfileChildren: 5, MaxWakes: 8}
	if m.Limits != expected || m.Facts.ProfileID == "" || m.Facts.CommandEpoch == "" || m.Facts.Schema < 1 {
		t.Fatal("fixture lacks its actual Profile/limits", m.Limits, m.Facts.ProfileID)
	}
	roots, rootRows, children := map[string]bool{}, map[string]bool{}, map[string]int{}
	for _, id := range m.Roots {
		if id == "" || roots[id] || m.Facts.RootLimits[id] != expected {
			t.Fatal("fixture root identity or persisted limits changed", id)
		}
		roots[id] = true
	}
	accepted, running := 0, 0
	runningByRoot := map[string]int{}
	seen := map[string]bool{}
	for _, r := range m.Facts.Runs {
		if r.ID == "" || seen[r.ID] || !roots[r.RootID] || r.Slot != 0 {
			t.Fatal("fixture lost original identities or stopped producer cleanup", r)
		}
		seen[r.ID] = true
		if r.ParentID == "" {
			if !roots[r.ID] || r.ID != r.RootID || r.State != "waiting_children" {
				t.Fatal("fixture changed original parent result phase", r)
			}
			rootRows[r.ID] = true
		} else {
			if r.ParentID != r.RootID {
				t.Fatal("fixture manufactured another tree level", r)
			}
			children[r.RootID]++
			switch r.State {
			case "accepted":
				accepted++
			case "running":
				running++
				runningByRoot[r.RootID]++
			default:
				t.Fatal("fixture child was manually recovered or terminalized", r)
			}
		}
	}
	for n, id := range m.Roots {
		wantRunning := 0
		if n < 5 {
			wantRunning = 1
		}
		if !rootRows[id] || children[id] != 32 || runningByRoot[id] != wantRunning {
			t.Fatal("fixture omitted original parent/children", id, children[id])
		}
	}
	if running != min(m.Trees, 5) || accepted != 32*m.Trees-running {
		t.Fatal("fixture changed actual held/never-claimed boundary", accepted, running)
	}
}

// Stage after real Close/Done, then publish only if the corresponding complete
// public construction/recovery/consumption case has passed all final assertions.
func fairnessStageFixture(t *testing.T, loc string, roots []string, trees int, limits api.ExecutionLimits) func() {
	t.Helper()
	m := claimFixtureManifest{Format: 1, Trees: trees, Roots: roots, Limits: limits, Facts: claimReadFixtureFacts(t, loc, roots)}
	claimVerifyFixtureFacts(t, m)
	m.GenerationSourceFiles, m.GenerationSourceSHA256 = claimGenerationSources(t)
	var compressed bytes.Buffer
	z := gzip.NewWriter(&compressed)
	a := tar.NewWriter(z)
	e := filepath.WalkDir(loc, func(path string, d os.DirEntry, err error) error {
		if err != nil || path == loc {
			return err
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		if !info.IsDir() && !info.Mode().IsRegular() {
			return fmt.Errorf("non-regular Profile fixture entry: %s", path)
		}
		rel, err := filepath.Rel(loc, path)
		if err != nil {
			return err
		}
		record := claimFixtureFile{Path: filepath.ToSlash(rel), Size: info.Size(), Mode: int64(info.Mode().Perm()), Directory: info.IsDir()}
		if record.Directory {
			record.Path += "/"
		}
		h, err := tar.FileInfoHeader(info, "")
		if err != nil {
			return err
		}
		h.Name = record.Path
		if err = a.WriteHeader(h); err != nil {
			return err
		}
		if info.IsDir() {
			record.Size = 0
		} else {
			b, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if int64(len(b)) != info.Size() {
				return fmt.Errorf("closed Profile fixture changed during capture: %s", rel)
			}
			record.SHA256 = claimDigest(b)
			if _, err = a.Write(b); err != nil {
				return err
			}
		}
		m.Files = append(m.Files, record)
		return nil
	})
	if e != nil {
		t.Fatal(e)
	}
	if e = a.Close(); e != nil {
		t.Fatal(e)
	}
	if e = z.Close(); e != nil {
		t.Fatal(e)
	}
	archive := append([]byte{}, compressed.Bytes()...)
	m.ArchiveSHA256 = claimDigest(archive)
	manifest, e := json.MarshalIndent(m, "", "  ")
	if e != nil {
		t.Fatal(e)
	}
	return func() {
		dir := claimFixtureDirectory(trees)
		if e := os.MkdirAll(dir, 0700); e != nil {
			t.Fatal(e)
		}
		// The manifest is the last publication marker. An interrupted update
		// fails its archive hash instead of presenting a mixed recovery input.
		for _, item := range []struct {
			name string
			data []byte
		}{{"profile.tar.gz", archive}, {"manifest.json", append(manifest, '\n')}} {
			path := filepath.Join(dir, item.name)
			if e := os.WriteFile(path+".new", item.data, 0600); e != nil {
				t.Fatal(e)
			}
			if e := os.Rename(path+".new", path); e != nil {
				t.Fatal(e)
			}
		}
		t.Logf("published synthetic %d-tree complete fixture after passing case: archive=%s generation=%s", trees, m.ArchiveSHA256, m.GenerationSourceSHA256)
	}
}

func fairnessLoadFixture(t *testing.T, loc string, trees int, limits api.ExecutionLimits) []string {
	t.Helper()
	dir := claimFixtureDirectory(trees)
	data, e := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if e != nil {
		t.Fatal("generate ordinary-mode complete fixtures first (see testdata/claim-fairness/README.md)", e)
	}
	var m claimFixtureManifest
	if e = json.Unmarshal(data, &m); e != nil {
		t.Fatal(e)
	}
	claimVerifyFixtureFacts(t, m)
	if m.Trees != trees || m.Limits != limits || len(m.GenerationSourceFiles) == 0 || claimSourceDigest(m.GenerationSourceFiles) != m.GenerationSourceSHA256 {
		t.Fatal("wrong fixture/provenance", trees, m.Trees)
	}
	archive, e := os.ReadFile(filepath.Join(dir, "profile.tar.gz"))
	if e != nil || claimDigest(archive) != m.ArchiveSHA256 || len(archive) > 16<<20 {
		t.Fatal("fixture archive digest/size mismatch", e)
	}
	z, e := gzip.NewReader(bytes.NewReader(archive))
	if e != nil {
		t.Fatal(e)
	}
	defer z.Close()
	a := tar.NewReader(z)
	expected, seen := map[string]claimFixtureFile{}, map[string]bool{}
	for _, f := range m.Files {
		if !filepath.IsLocal(f.Path) || expected[f.Path].Path != "" || f.Size < 0 || f.Size > 16<<20 {
			t.Fatal("invalid complete fixture file declaration", f.Path)
		}
		expected[f.Path] = f
	}
	dbFile, dbPresent := expected["profile.sqlite3"]
	if len(expected) == 0 || len(expected) > 128 || !dbPresent || dbFile.Directory {
		t.Fatal("fixture omitted its DB or exceeded its bounded inventory")
	}
	if e = os.MkdirAll(loc, 0700); e != nil {
		t.Fatal(e)
	}
	var total int64
	for {
		h, e := a.Next()
		if e == io.EOF {
			break
		}
		if e != nil {
			t.Fatal(e)
		}
		f, ok := expected[h.Name]
		if !ok || seen[h.Name] || !filepath.IsLocal(h.Name) || (h.Typeflag != tar.TypeReg && h.Typeflag != tar.TypeDir) || (h.Typeflag == tar.TypeDir) != f.Directory || h.Mode != f.Mode || f.Mode&0077 != 0 {
			t.Fatal("fixture archive contains unbound/repeated entry", h.Name)
		}
		seen[h.Name] = true
		path := filepath.Join(loc, filepath.FromSlash(h.Name))
		if f.Directory {
			if e = os.MkdirAll(path, 0700); e != nil {
				t.Fatal(e)
			}
			continue
		}
		if h.Size != f.Size {
			t.Fatal("fixture file size changed", h.Name)
		}
		total += h.Size
		if total > 64<<20 {
			t.Fatal("complete fixture exceeds bounded size")
		}
		b, e := io.ReadAll(a)
		if e != nil || int64(len(b)) != f.Size || claimDigest(b) != f.SHA256 {
			t.Fatal("fixture file digest mismatch", h.Name, e)
		}
		if e = os.MkdirAll(filepath.Dir(path), 0700); e != nil {
			t.Fatal(e)
		}
		if e = os.WriteFile(path, b, os.FileMode(f.Mode)); e != nil {
			t.Fatal(e)
		}
	}
	if len(seen) != len(expected) {
		t.Fatal("incomplete Profile fixture archive", len(seen), len(expected))
	}
	if actual := claimReadFixtureFacts(t, loc, m.Roots); !reflect.DeepEqual(actual, m.Facts) {
		t.Fatal("copied fixture changed actual Run/phase/limit facts", actual)
	}
	t.Logf("copied full ordinary-mode synthetic %d-tree Profile; archive=%s source=%s originalRuns=%d", trees, m.ArchiveSHA256, m.GenerationSourceSHA256, len(m.Facts.Runs))
	return append([]string{}, m.Roots...)
}
