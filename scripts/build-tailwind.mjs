// scripts/build-tailwind.mjs
// 用法：
//   node scripts/build-tailwind.mjs                    正式构建 → build/tailwind.scoped.css + 字体 CSS
//   node scripts/build-tailwind.mjs --skip-compile     不重新编译，只对现有 build/tailwind.raw.css 做作用域（dev 用）
//   node scripts/build-tailwind.mjs --write-styles     完成后执行 build-styles.mjs --write（dev 用）
//   node scripts/build-tailwind.mjs --test-hover --out <文件>
//                                                      样式测试构建：hover 不包媒体查询；
//                                                      把“令牌 + 基础 + 中和层 + 工具类”拼成一个文件写到 <文件>
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import postcss from 'postcss';
import { scopeTailwind } from './scope-tailwind.mjs';

const argv = process.argv.slice(2);
const has = (name) => argv.includes(name);
const out = has('--out') ? argv[argv.indexOf('--out') + 1] : null;
const testHover = has('--test-hover');

// 用 node 直接运行 CLI 入口，Windows 上也不需要 .cmd 包装
const require = createRequire(import.meta.url);
const CLI = path.join(path.dirname(require.resolve('@tailwindcss/cli/package.json')), 'dist', 'index.mjs');

fs.mkdirSync('build', { recursive: true });
let entry = 'src/ui/tailwind/index.css';
const RAW = testHover ? 'build/tailwind.test.raw.css' : 'build/tailwind.raw.css';
if (testHover) {
	// 无头 Chrome 里 (hover: hover) 为假，Tailwind 默认的 hover: 规则不会生效。
	// 测试构建用一个入口文件覆盖 hover 变体（@source 仍按 index.css 自己的位置解析）。
	entry = 'build/tailwind.test-entry.css';
	fs.writeFileSync(entry, '@import "../src/ui/tailwind/index.css";\n@custom-variant hover (&:hover);\n');
}
if (!has('--skip-compile')) execFileSync(process.execPath, [CLI, '-i', entry, '-o', RAW, '--optimize'], { stdio: 'inherit' });

const scoped = (await postcss([scopeTailwind()]).process(fs.readFileSync(RAW, 'utf8'), { from: RAW })).css;

if (out) {
	const parts = ['src/ui/styles/tokens.css', 'src/ui/styles/base.css', 'src/ui/styles/neutralize.css'].map((file) => fs.readFileSync(file, 'utf8'));
	fs.writeFileSync(out, [...parts, scoped].join('\n'));
} else {
	fs.writeFileSync('build/tailwind.scoped.css', `/* GENERATED by scripts/build-tailwind.mjs — do not edit */\n${scoped}`);
	writeFontFaces();
	if (has('--write-styles')) execFileSync(process.execPath, ['scripts/build-styles.mjs', '--write'], { stdio: 'inherit' });
}

function writeFontFaces() {
	const faces = [
		{ family: 'Geist', file: 'src/ui/fonts/Geist-Variable.woff2', weight: '100 900', style: 'normal' },
		{ family: 'Geist Mono', file: 'src/ui/fonts/GeistMono-Variable.woff2', weight: '100 900', style: 'normal' },
		...JSON.parse(fs.readFileSync('src/theme/fonts/faces.json', 'utf8')).map((face) => ({ ...face, file: `src/theme/fonts/${face.file}` })),
	].map(({ family, file, weight, style }) =>
		`@font-face { font-family: "${family}"; src: url(data:font/woff2;base64,${fs.readFileSync(file).toString('base64')}) format("woff2"); font-weight: ${weight}; font-style: ${style}; font-display: swap; }`,
	);
	const next = `/* GENERATED by scripts/build-tailwind.mjs — do not edit. Fonts: SIL OFL 1.1 (src/ui/fonts/LICENSE.txt and src/theme/fonts/LICENSE.txt) */\n${faces.join('\n')}\n`;
	const file = 'src/ui/styles/fonts.generated.css';
	// 内容没变就不写，避免 dev 模式下无意义的重建
	if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== next) fs.writeFileSync(file, next);
}
