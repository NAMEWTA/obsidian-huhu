import { readFileSync } from 'node:fs';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { sonnerStyles } from './sonner-styles.mjs';
import { radixOwnerDocument } from './radix-owner-document.mjs';
import { draggableOwnerRealm } from './draggable-owner-realm.mjs';
import { canonicalTextResources, normalizeBuildText } from './build-text-resources.mjs';
import { versioningWorkerSource } from './versioning-worker.mjs';

const root = path.resolve(import.meta.dirname, '..');

function notice(relative) {
	return normalizeBuildText(readFileSync(path.join(root, relative), 'utf8')).replaceAll('*/', '* /');
}

const nodeBuiltins = [
	...builtinModules,
	...builtinModules.map((moduleName) => `node:${moduleName}`),
];

/** Shared esbuild options for the plugin bundle, used by the build and by bundle analysis. */
export function pluginBuildOptions({ production }) {
	// Include JS, embedded CSS and font notices in the self-contained plugin.
	// The helper's crate notices are supplied with the helper release.
	const thirdParty = notice('THIRD-PARTY-NOTICES.md');
	const bundled = thirdParty.slice(thirdParty.indexOf('## Bundled in main.js'), thirdParty.indexOf('## Linked into huhu-pty'));
	const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
HUHU source: https://github.com/NAMEWTA/obsidian-huhu

${notice('LICENSE')}

${notice('NOTICE')}

${notice('src/modules/icons/core/res/NOTICE.txt')}

SuliWorld theme:
${notice('third-party/suliworld/LICENSE')}

GitHub editor theme:
${notice('third-party/github-theme/LICENSE')}

Orca:
${notice('docs/third-party/orca-LICENSE.txt')}

${bundled}*/
`;
	return {
		absWorkingDir: root,
		banner: {
			js: banner,
		},
		entryPoints: ['src/app/main.ts'],
		bundle: true,
		jsx: 'automatic',
		jsxImportSource: 'react',
		loader: {
			'.md': 'text',
			'.svg': 'text',
		},
		external: [
			'obsidian',
			'electron',
			'@codemirror/autocomplete',
			'@codemirror/collab',
			'@codemirror/commands',
			'@codemirror/language',
			'@codemirror/lint',
			'@codemirror/search',
			'@codemirror/state',
			'@codemirror/view',
			'@lezer/common',
			'@lezer/highlight',
			'@lezer/lr',
			...nodeBuiltins,
		],
		plugins: [canonicalTextResources, sonnerStyles, radixOwnerDocument, draggableOwnerRealm, versioningWorkerSource],
		format: 'cjs',
		target: 'es2021',
		logLevel: 'info',
		sourcemap: production ? false : 'inline',
		treeShaking: true,
		outfile: 'main.js',
		minify: production,
		// Obsidian loads UTF-8 scripts. Avoid expanding every localized character to an ASCII escape.
		charset: 'utf8',
	};
}
