// Regenerates pi-artifact-profiles.generated.ts from pi-artifact-profiles.json (the source of truth).
// Usage: node scripts/generate-pi-artifact-profiles.mjs [--check]. The JSON itself is never bundled.
import fs from 'node:fs';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const dir = new URL('../src/modules/agent/platform/desktop/agents/', import.meta.url);
const source = JSON.parse(fs.readFileSync(new URL('pi-artifact-profiles.json', dir), 'utf8'));
const packed = zlib
	.brotliCompressSync(Buffer.from(JSON.stringify(source), 'utf8'), {
		params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11, [zlib.constants.BROTLI_PARAM_SIZE_HINT]: 0 },
	})
	.toString('base64');
const content =
	'// Generated by scripts/generate-pi-artifact-profiles.mjs from pi-artifact-profiles.json; do not edit.\n' +
	'// brotli stream of the minified JSON, base64; decoded in program-identity.ts.\n' +
	`export const PI_ARTIFACT_PROFILES_BROTLI_BASE64 =\n\t'${packed}';\n`;
const file = fileURLToPath(new URL('pi-artifact-profiles.generated.ts', dir));
if (process.argv.includes('--check')) {
	// zlib output may vary between versions, so compare the decoded meaning, not the bytes.
	const match = /'([A-Za-z0-9+/=]+)'/.exec(fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '');
	const decoded = match && JSON.parse(zlib.brotliDecompressSync(Buffer.from(match[1], 'base64')).toString('utf8'));
	if (JSON.stringify(decoded) !== JSON.stringify(source))
		throw new Error('pi-artifact-profiles.generated.ts is stale');
	console.log('pi artifact profiles asset matches');
} else {
	fs.writeFileSync(file, content);
	console.log('pi artifact profiles asset generated');
}
